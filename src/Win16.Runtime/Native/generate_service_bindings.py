#!/usr/bin/env python3
"""Generate explicit native import routing from shared service binding metadata."""
import argparse
import json
from pathlib import Path
from native_source import format_c

ROOT = Path(__file__).resolve().parent
MODULES = {"KERNEL": 1, "USER": 2, "GDI": 3, "WEP4UTIL": 4}


def render():
    rows = json.loads((ROOT.parent / "Win16TaskServiceBindings.json").read_text())
    contracts = {
        f"{c['Module']}.#{c['Ordinal']}": c
        for c in json.loads((ROOT.parent / "Win16ExportContracts.json").read_text())
    }
    seen = set()
    lines = [
        "/* Generated by generate_service_bindings.py; metadata is not service acceptance. */",
        "ABI NOINLINE u16 __win16_import_dispatch(Runtime *r,State *s,u16 module,u16 ordinal)",
        "{",
        "    if(r->error)return 0;",
        "    switch(((u32)module<<16)|ordinal){",
    ]
    for row in sorted(rows, key=lambda r: r["Identity"]):
        identity = row["Identity"]
        contract = contracts[identity]
        if identity in seen or contract["Kind"] == "Constant":
            raise ValueError("Duplicate or constant callable binding: " + identity)
        seen.add(identity)
        module = MODULES[contract["Module"]]
        export = row["NativeExport"]
        if not export.startswith("__win16_") or not export.replace("_", "").isalnum():
            raise ValueError("Invalid native export: " + export)
        args = {
            "State": "r,s",
            "Ordinal": "r,s,ordinal",
            "ModuleOrdinal": "r,s,module,ordinal",
        }[row["Invocation"]]
        lines.append(
            f"    case 0x{module:04x}{contract['Ordinal']:04x}u: return {export}({args}); /* {identity} */"
        )
    lines += ["    default:r->error=14;return 0;", "    }", "}", ""]
    return format_c("\n".join(lines))


def render_gui_plans():
    """Derive native GUI layouts from the contracts also consumed by managed services."""
    plans = json.loads((ROOT.parent / "Win16GuiPlans.json").read_text())
    contracts = {
        f"{c['Module']}.#{c['Ordinal']}": c
        for c in json.loads((ROOT.parent / "Win16ExportContracts.json").read_text())
    }
    kinds = {"u": 1, "s": 2, "l": 3, "text": 4, "h": 5, "d": 6, "g": 7, "m": 8, "c": 9}
    results = {
        "void": 0,
        "word": 1,
        "long": 2,
        "h": 5,
        "d": 6,
        "g": 7,
        "m": 8,
        "c": 9,
        "owned-d": 38,
        "muldiv": 40,
    }

    def argument_type(token):
        owned = token.startswith("owned-")
        kind = token[6:] if owned else token
        optional = kind.endswith("?")
        return kinds[kind.rstrip("?")] | (32 if owned else 0) | (16 if optional else 0)

    def array(values):
        return "{" + (",".join(map(str, values)) or "0") + "}"

    lines = [
        "/* Generated from Win16GuiPlans.json and pinned export contracts. */",
        "typedef struct { u16 module,ordinal,count,result; u32 failure; short release; u16 types[11],words[11],widths[11]; } GuiPlan;",
        "static const GuiPlan gui_plans[] = {",
    ]
    seen = set()
    for plan in plans:
        identity = f"{plan['Module']}.#{plan['Ordinal']}"
        contract = contracts[identity]
        arguments = contract["Arguments"]
        if (
            identity in seen
            or len(arguments) != len(plan["Arguments"])
            or len(arguments) > 11
        ):
            raise ValueError("Invalid or duplicate GUI plan: " + identity)
        seen.add(identity)
        if (
            contract["Kind"] == "Constant"
            or contract["Convention"] != "Pascal"
            or contract["Variadic"]
            or contract["CleanupBytes"] != sum(a["Bytes"] for a in arguments)
        ):
            raise ValueError("Unsupported GUI calling convention: " + identity)
        if plan["ReleaseArgument"] < -1 or plan["ReleaseArgument"] >= len(arguments):
            raise ValueError("Invalid GUI release argument: " + identity)
        fields = [
            MODULES[plan["Module"]],
            plan["Ordinal"],
            len(arguments),
            results[plan["Result"]],
            str(plan["Failure"]) + "u",
            plan["ReleaseArgument"],
            array(argument_type(a) for a in plan["Arguments"]),
            array(a["StackWord"] for a in arguments),
            array(a["Bytes"] for a in arguments),
        ]
        lines.append("    {" + ",".join(map(str, fields)) + "},")
    return format_c("\n".join(lines + ["};", ""]))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, expected in (
        ("task_import_dispatch.h", render()),
        ("task_gui_plans.h", render_gui_plans()),
    ):
        target = ROOT / name
        if args.check:
            if target.read_text() != expected:
                raise SystemExit(f"Stale {name}; run generate_service_bindings.py")
        else:
            target.write_text(expected)
